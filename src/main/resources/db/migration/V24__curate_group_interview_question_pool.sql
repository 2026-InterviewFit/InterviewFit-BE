-- 기존 질문과 답변 참조는 삭제하지 않는다. 정확히 중복된 행은 신규 출제에서만 제외한다.
WITH ranked AS (
    SELECT id,
           ROW_NUMBER() OVER (
               PARTITION BY round_number, COALESCE(job_role_id, 0), REGEXP_REPLACE(TRIM(question_text), '\s+', ' ', 'g')
               ORDER BY id
           ) AS duplicate_order
    FROM group_questions
)
UPDATE group_questions q
SET selection_enabled = FALSE
FROM ranked r
WHERE q.id = r.id AND r.duplicate_order > 1;

-- 구 3라운드 구조에 남은 직무 질문은 원본을 보존한 채 4라운드 활성 질문으로 복사한다.
INSERT INTO group_questions (job_role_id, round_number, question_text, created_at, selection_enabled)
SELECT DISTINCT source.job_role_id, 4, source.question_text, CURRENT_TIMESTAMP, TRUE
FROM group_questions source
WHERE source.job_role_id IS NOT NULL
  AND source.round_number <> 4
  AND NOT EXISTS (
      SELECT 1 FROM group_questions target
      WHERE target.round_number = 4
        AND target.job_role_id = source.job_role_id
        AND target.question_text = source.question_text
  );

UPDATE group_questions
SET selection_enabled = FALSE
WHERE job_role_id IS NOT NULL AND round_number <> 4;

